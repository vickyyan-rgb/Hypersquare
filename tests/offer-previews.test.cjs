const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.join(__dirname,'../dist');
const file=path.join(root,'offer-previews.js');
assert(fs.existsSync(file),'Bank offers need hover previews');
let timers=new Map(),next=0,active=null,listeners={};
function node(rect={left:100,top:250,bottom:330,width:160,height:80}){return {hidden:true,style:{},attrs:{},dataset:{},innerHTML:'',getBoundingClientRect:()=>rect,setAttribute(k,v){this.attrs[k]=String(v);},contains(el){return el===this||el===this.child;},focus(){active=this;this.onfocus?.();}};}
const choose=node(),close=node(),content=node(),preview=node({width:420,height:480});
preview.child=choose;preview.querySelector=selector=>selector==='[data-choose-offer]'?choose:null;
const tiles=['boa','chase','amex','citi','wells','capital'].map((id,i)=>Object.assign(node({left:i===5?1110:100+i*160,top:250,bottom:330,width:160,height:80}),{dataset:{bank:id}}));
const ids={'bank-offer-preview':preview,'bank-preview-content':content,'bank-preview-close':close};
const context={document:{getElementById:id=>ids[id],querySelectorAll:()=>tiles,get activeElement(){return active;}},window:{innerWidth:1280,innerHeight:900,addEventListener:(name,fn)=>listeners[name]=fn},location:{hash:'#/offers'},dialog:{open:false,close(){this.open=false;}},setTimeout(fn){timers.set(++next,fn);return next;},clearTimeout(id){timers.delete(id);}};
vm.createContext(context);
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
vm.runInContext(app.slice(0,app.indexOf('const app=')),context);
vm.runInContext(fs.readFileSync(file,'utf8'),context);
const read=s=>vm.runInContext(s,context);
const flush=()=>{for(const [id,fn] of timers){timers.delete(id);fn();}};
context.bindBankPreviews();
tiles[0].onpointerenter({pointerType:'mouse'});
assert.equal(preview.hidden,false);assert.equal(tiles[0].attrs['aria-expanded'],'true');
assert(content.innerHTML.includes(read('plans[0].description')));
assert.equal(content.innerHTML,context.bankOfferContent('boa','bank-preview-title'));
tiles[0].onpointerleave();preview.onpointerenter();flush();assert.equal(preview.hidden,false,'Pointer can cross from logo to preview');
preview.onpointerleave();flush();assert.equal(preview.hidden,true);
tiles[5].onfocus();assert.equal(preview.hidden,false);assert.equal(tiles[0].attrs['aria-expanded'],'false');
assert(parseFloat(preview.style.left)+420<=1280-12,'Rightmost offer must fit within the viewport');
let prevented=false;tiles[5].onkeydown({key:'ArrowDown',preventDefault(){prevented=true;}});assert(prevented);assert.equal(active,choose);
listeners.keydown({key:'Escape',preventDefault(){}});assert.equal(preview.hidden,true);assert.equal(active,tiles[5],'Escape returns focus without reopening');
tiles[0].onpointerenter({pointerType:'touch'});assert.equal(preview.hidden,true,'Touch keeps click-based details');
tiles[1].onpointerenter({pointerType:'mouse'});choose.onclick();assert.equal(read('state.plan'),'chase');assert.equal(context.location.hash,'/register');assert.equal(preview.hidden,true);
tiles[2].onpointerenter({pointerType:'mouse'});tiles[2].onpointerleave();context.closeBankPreview();flush();assert.equal(preview.hidden,true);
const modalContent=node();
context.document.querySelector=selector=>selector==='#dialog-content'?modalContent:null;
context.dialog.showModal=function(){this.open=true;};
context.dialog.querySelector=selector=>selector==='[data-choose-offer]'?choose:null;
vm.runInContext(app.slice(app.indexOf('function showDialog('),app.indexOf('function openInfo(')),context);
tiles[3].onpointerenter({pointerType:'mouse'});context.openBank('citi');
assert.equal(preview.hidden,true);assert.equal(context.dialog.open,true);
assert.equal(modalContent.innerHTML,context.bankOfferContent('citi','dialog-title'),'Click and hover share the same offer details');
choose.onclick();assert.equal(read('state.plan'),'citi');assert.equal(context.dialog.open,false);
console.log('Passed: offer hover content, pointer handoff, dismissal, keyboard access, viewport placement, touch fallback, click dialog, and plan selection.');
